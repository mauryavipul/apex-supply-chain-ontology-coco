USE DATABASE SC_ONTOLOGY;
USE SCHEMA CURATED;
USE WAREHOUSE HACK_WH;

-- 1. Conformed Date Dimension (Base table: RAW.ERP_INVENTORY_SNAPSHOTS)
CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_DATE
    TARGET_LAG = '1 day'
    WAREHOUSE = HACK_WH
AS
SELECT 
    TO_NUMBER(TO_VARCHAR(d_date, 'YYYYMMDD')) AS DATE_KEY,
    d_date AS FULL_DATE,
    EXTRACT(year FROM d_date) AS YEAR,
    'Q' || EXTRACT(quarter FROM d_date) AS QUARTER,
    'Q' || EXTRACT(quarter FROM d_date) || ' ' || EXTRACT(year FROM d_date) AS QUARTER_YEAR,
    EXTRACT(month FROM d_date) AS MONTH_NUM,
    TO_VARCHAR(d_date, 'MMMM') AS MONTH_NAME,
    TO_VARCHAR(d_date, 'YYYY-MM') AS YEAR_MONTH,
    EXTRACT(week FROM d_date) AS WEEK_OF_YEAR,
    DAYNAME(d_date) AS DAY_NAME,
    CASE WHEN EXTRACT(dayofweek FROM d_date) IN (0, 6) THEN TRUE ELSE FALSE END AS IS_WEEKEND
FROM (
    SELECT DISTINCT COALESCE(TRY_TO_DATE(SNAP_DATE_STR, 'YYYY-MM-DD'), TRY_TO_DATE(SNAP_DATE_STR, 'DD/MM/YYYY')) AS d_date
    FROM RAW.ERP_INVENTORY_SNAPSHOTS
    WHERE SNAP_DATE_STR IS NOT NULL
);

-- 2. Conformed Plant Dimension
CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_PLANT
    TARGET_LAG = '1 day'
    WAREHOUSE = HACK_WH
AS
SELECT 
    HASH(PLANT_CODE) AS PLANT_KEY,
    PLANT_CODE,
    PLANT_NAME,
    CITY,
    COUNTRY_CODE AS COUNTRY,
    REGION,
    TZ_OFFSET AS TIMEZONE
FROM RAW.ERP_PLANTS;

-- 3. Conformed Supplier Dimension (Resolves 3 different IDs into canonical SUPPLIER_KEY)
CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_SUPPLIER
    TARGET_LAG = '1 day'
    WAREHOUSE = HACK_WH
AS
SELECT 
    HASH(VENDOR_ID) AS SUPPLIER_KEY,
    VENDOR_ID AS SUPPLIER_ID,
    VENDOR_NAME AS SUPPLIER_NAME,
    TIER_CODE AS SUPPLIER_TIER,
    COUNTRY,
    CASE 
        WHEN COUNTRY IN ('USA', 'Canada', 'Mexico') THEN 'AMER'
        WHEN COUNTRY IN ('Germany', 'United Kingdom', 'France') THEN 'EMEA'
        ELSE 'APAC'
    END AS REGION,
    STATUS_FLAG AS STATUS
FROM RAW.ERP_SUPPLIERS;

-- 4. Conformed Part Dimension (Standardized Standard Cost in USD)
CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_PART
    TARGET_LAG = '1 day'
    WAREHOUSE = HACK_WH
AS
SELECT 
    HASH(p.MATERIAL_NO) AS PART_KEY,
    p.MATERIAL_NO AS PART_NUMBER,
    p.DESCRIPTION AS PART_NAME,
    p.COMMODITY_GROUP AS PART_CATEGORY,
    p.BASE_UOM AS UNIT_OF_MEASURE,
    ROUND(p.STD_COST_LOCAL * COALESCE(fx.EXCHANGE_RATE, 1.000000), 2) AS STANDARD_COST_USD,
    CASE WHEN p.IS_CRITICAL_FLAG = 'Y' THEN TRUE ELSE FALSE END AS IS_CRITICAL
FROM RAW.ERP_PARTS p
LEFT JOIN RAW.FX_RATES fx 
    ON p.LOCAL_CURR = fx.BASE_CURRENCY 
   AND fx.YEAR_MONTH = '2025-10';

